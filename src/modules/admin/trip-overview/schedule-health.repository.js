"use strict";

const Trip = require("../../../../models/tripModel");
const Schedule = require("../../../../models/scheduleModel");

const findSchedules = (brandFilter) =>
  Schedule.find({
    ...brandFilter,
    status: { $in: ["ACTIVE", "SUSPENDED"] },
  })
    .populate("brandId", "brandName brandCode logo")
    .populate("busId", "busNumber busName totalSeats")
    .populate("driverId", "fullName status")
    .populate({
      path: "variantId",
      select: "code name direction",
      populate: {
        path: "corridorId",
        select: "originCity destinationCity",
        populate: [
          { path: "originId", select: "name" },
          { path: "destinationId", select: "name" },
        ],
      },
    })
    .sort({ status: 1, "brandId.brandName": 1 })
    .lean();

const findTripEdge = (scheduleId, direction, filter = {}, projection) =>
  Trip.findOne({ scheduleId, ...filter })
    .sort(direction)
    .select(projection)
    .lean();

const loadScheduleTripStats = async (scheduleId, todayEnd, thirtyDaysAgo) => {
  const [
    farthestTrip,
    firstTrip,
    lastGeneratedTrip,
    totalTrips,
    upcomingTrips,
    cancelledTrips,
  ] = await Promise.all([
    findTripEdge(
      scheduleId,
      { tripDate: -1 },
      { status: { $ne: "cancelled" } },
      "tripDate tripId"
    ),
    findTripEdge(scheduleId, { tripDate: 1 }, {}, "tripDate"),
    findTripEdge(
      scheduleId,
      { createdAt: -1 },
      { isAutoGenerated: true },
      "tripDate createdAt tripId"
    ),
    Trip.countDocuments({ scheduleId }),
    Trip.countDocuments({
      scheduleId,
      tripDate: { $gt: todayEnd },
      status: "scheduled",
    }),
    Trip.countDocuments({
      scheduleId,
      tripDate: { $gte: thirtyDaysAgo },
      status: "cancelled",
    }),
  ]);
  return {
    farthestTrip,
    firstTrip,
    lastGeneratedTrip,
    totalTrips,
    upcomingTrips,
    cancelledTrips,
  };
};

const findExistingTripDates = async (scheduleId, start, end) => {
  const trips = await Trip.find({
    scheduleId,
    tripDate: { $gte: start, $lte: end },
    status: { $ne: "cancelled" },
  })
    .select("tripDate")
    .lean();
  return new Set(
    trips.map((trip) => new Date(trip.tripDate).toISOString().split("T")[0])
  );
};

module.exports = {
  findSchedules,
  loadScheduleTripStats,
  findExistingTripDates,
};
